#!/usr/bin/env python3
"""Compare generated trees outside the three intended swapchain decoder cases."""
from pathlib import Path
import re
import sys

base, candidate = map(Path, sys.argv[1:])

def normalize(path, contents):
    contents = re.sub(r'// \((?:impl|header)\) generated by.*?// Please do not modify directly;',
                      '// GENERATED', contents, flags=re.S)
    if str(path).replace('\\', '/') == 'host/VkDecoder.cpp':
        for name in ('vkCreateSwapchainKHR', 'vkDestroySwapchainKHR', 'vkGetSwapchainImagesKHR'):
            contents, count = re.subn(r'case OP_' + name + r':.*?(?=case OP_)',
                                      'case OP_' + name + ': OMITTED\n', contents, count=1, flags=re.S)
            if count != 1:
                raise ValueError(f'missing decoder case {name}')
    return contents

base_files = {p.relative_to(base) for sub in ('host', 'guest') for p in (base / sub).rglob('*') if p.is_file()}
other_files = {p.relative_to(candidate) for sub in ('host', 'guest') for p in (candidate / sub).rglob('*') if p.is_file()}
if base_files != other_files:
    raise SystemExit('generated file sets differ')
different = [p for p in sorted(base_files) if normalize(p, (base / p).read_text()) != normalize(p, (candidate / p).read_text())]
if different:
    raise SystemExit('unexpected generated differences: ' + ', '.join(map(str, different)))
print('GENERATED_SCOPE_ONLY_THREE_SWAPCHAIN_CASES_OK')
